//! Publish deterministic, synthetic interoperability fixtures, never production keys.
use base64::{Engine, engine::general_purpose::STANDARD as B64};
use serde_json::json;
use voiceremote_core::{
    Result,
    pairing::{PATTERN, prologue, verification_phrase},
    protocol::*,
};

#[test]
fn published_xx_pairing_vector_matches() -> Result<()> {
    let si = [0x11; 32];
    let sr = [0x22; 32];
    let ei = [0x33; 32];
    let er = [0x44; 32];
    let token = [0x55; 32];
    let responder_public = x25519_dalek::x25519(sr, x25519_dalek::X25519_BASEPOINT_BYTES);
    let payload = PairingPayload {
        kind: PairingPayloadKind::Pairing,
        account_id: "synthetic-account".into(),
        desktop_public_key: B64.encode(responder_public),
        one_use_token: B64.encode(token),
        expires_at: 120001,
        relay_room_id: "synthetic-room".into(),
    };
    let prologue = prologue(&payload)?;
    let mut i = voiceremote_core::pairing::noise_builder()?
        .local_private_key(&si)?
        .fixed_ephemeral_key_for_testing_only(&ei)
        .prologue(&prologue)?
        .build_initiator()?;
    let mut r = voiceremote_core::pairing::noise_builder()?
        .local_private_key(&sr)?
        .fixed_ephemeral_key_for_testing_only(&er)
        .prologue(&prologue)?
        .build_responder()?;
    let mut buffer = [0; 65535];
    let mut plain = [0; 65535];
    let mut messages = vec![];
    let n = i.write_message(&[], &mut buffer)?;
    messages.push(hex::encode(&buffer[..n]));
    assert_eq!(r.read_message(&buffer[..n], &mut plain)?, 0);
    let n = r.write_message(&[], &mut buffer)?;
    messages.push(hex::encode(&buffer[..n]));
    assert_eq!(i.read_message(&buffer[..n], &mut plain)?, 0);
    assert_eq!(i.get_remote_static(), Some(responder_public.as_slice()));
    let n = i.write_message(&token, &mut buffer)?;
    messages.push(hex::encode(&buffer[..n]));
    let m = r.read_message(&buffer[..n], &mut plain)?;
    assert_eq!(&plain[..m], &token);
    assert_eq!(i.get_handshake_hash(), r.get_handshake_hash());
    let hash = i.get_handshake_hash().to_vec();
    let phrase = verification_phrase(&hash);
    let mut i = i.into_transport_mode()?;
    let mut r = r.into_transport_mode()?;
    let device = |id: &str, platform| DeviceInfo {
        kind: DeviceInfoKind::DeviceInfo,
        account_id: "synthetic-account".into(),
        device_id: id.into(),
        display_name: "Synthetic peer".into(),
        platform,
        role: DeviceInfoRole::TextReceiver,
        capabilities: vec![Capability::ReceiveText],
    };
    let mut pc = vec![1];
    pc.extend_from_slice(&hash);
    pc.extend_from_slice(
        encode(&device("phone", DeviceInfoPlatform::Ios))
            .map_err(anyhow::Error::msg)?
            .as_bytes(),
    );
    let mut dc = vec![1];
    dc.extend_from_slice(&hash);
    dc.extend_from_slice(
        encode(&device("desktop", DeviceInfoPlatform::Linux))
            .map_err(anyhow::Error::msg)?
            .as_bytes(),
    );
    let n = i.write_message(&pc, &mut buffer)?;
    let ic = hex::encode(&buffer[..n]);
    let m = r.read_message(&buffer[..n], &mut plain)?;
    assert_eq!(&plain[..m], &pc);
    let n = r.write_message(&dc, &mut buffer)?;
    let rc = hex::encode(&buffer[..n]);
    let m = i.read_message(&buffer[..n], &mut plain)?;
    assert_eq!(&plain[..m], &dc);
    let application = encode(&DictationText {
        kind: DictationTextKind::DictationText,
        account_id: "synthetic-account".into(),
        segment_id: "synthetic-segment".into(),
        revision: 1,
        state: DictationTextState::Committed,
        target_device_id: "desktop".into(),
        text: "Synthetic sample".into(),
    })
    .map_err(anyhow::Error::msg)?;
    let n = i.write_message(application.as_bytes(), &mut buffer)?;
    let encrypted = hex::encode(&buffer[..n]);
    let m = r.read_message(&buffer[..n], &mut plain)?;
    assert_eq!(&plain[..m], application.as_bytes());
    let vector = json!({"purpose":"Synthetic interoperability fixture; public test secrets only; generated by snow 0.10.0", "pattern":PATTERN, "initiator_static_private_hex":hex::encode(si),"responder_static_private_hex":hex::encode(sr), "initiator_ephemeral_private_hex":hex::encode(ei), "responder_ephemeral_private_hex":hex::encode(er), "qr_payload": payload, "prologue_hex":hex::encode(prologue), "handshake_messages_hex":messages, "handshake_hash_hex":hex::encode(hash), "verification_phrase":phrase, "initiator_confirmation_plaintext_hex":hex::encode(pc), "responder_confirmation_plaintext_hex":hex::encode(dc), "initiator_confirmation_ciphertext_hex":ic,"responder_confirmation_ciphertext_hex":rc,"application_plaintext":application,"application_ciphertext_hex":encrypted});
    let output = serde_json::to_string_pretty(&vector)? + "\n";
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../../../SYS/protocol/vectors/noise/xx-pairing.json");
    if std::env::var_os("VOICEREMOTE_UPDATE_NOISE_VECTORS").is_some() {
        std::fs::write(&path, &output)?;
    }
    assert_eq!(
        std::fs::read_to_string(path)?,
        output,
        "regenerate only after reviewing the protocol change"
    );
    let mut fragments = Vec::new();
    let mut assembled = Vec::new();
    let bytes = application.as_bytes();
    let split = bytes.len() / 2;
    for (offset, chunk) in [(0, &bytes[..split]), (split, &bytes[split..])] {
        let mut plain_fragment = vec![3];
        plain_fragment.extend_from_slice(&(bytes.len() as u32).to_be_bytes());
        plain_fragment.extend_from_slice(&(offset as u32).to_be_bytes());
        plain_fragment.extend_from_slice(chunk);
        let n = i.write_message(&plain_fragment, &mut buffer)?;
        fragments.push(json!({"offset":offset,"plaintext_hex":hex::encode(&plain_fragment),"ciphertext_hex":hex::encode(&buffer[..n])}));
        let m = r.read_message(&buffer[..n], &mut plain)?;
        assert_eq!(&plain[..m], plain_fragment);
        assembled.extend_from_slice(&plain[9..m]);
    }
    assert_eq!(assembled, bytes);
    let output = serde_json::to_string_pretty(
        &json!({"purpose":"Synthetic fragment encoding fixture; continues xx-pairing.json after application nonce 1","pattern":PATTERN,"initiator_nonces":[2,3],"total_bytes":bytes.len(),"reassembled_plaintext":application,"fragments":fragments}),
    )? + "\n";
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../../../SYS/protocol/vectors/noise/xx-fragments.json");
    if std::env::var_os("VOICEREMOTE_UPDATE_NOISE_VECTORS").is_some() {
        std::fs::write(&path, &output)?;
    }
    assert_eq!(std::fs::read_to_string(path)?, output);
    Ok(())
}
